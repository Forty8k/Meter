#!/usr/bin/env python3
"""Builds src/OriginalScorer.inc from the untouched Airwindows Meter 0.5.5 sources in ../original.
The original code is copied word for word (header struct, paint(), mouseDown(), and the editor's per-window
INCREMENT handler), wrapped in namespace f8korig so it compiles against the stand-ins in OriginalStub.h.
Run it again if the files in ../original are ever replaced: nothing in the output is edited by hand."""
import pathlib, re
here = pathlib.Path(__file__).resolve().parent.parent
orig = here / "original"
h = (orig / "AirwindowsUI.h").read_text().split("\n")
c = (orig / "AirwindowsUI.cpp").read_text().split("\n")
e = (orig / "PluginEditor.cpp").read_text().split("\n")

start = next(i for i, l in enumerate(h) if l.startswith("struct AirwindowsMeter"))
end = next(i for i in range(start, len(h)) if h[i].startswith("};"))
struct = h[start:end + 1]

cstart = next(i for i, l in enumerate(c) if l.startswith("void AirwindowsMeter::mouseDown"))
body = c[cstart:]

istart = next(i for i, l in enumerate(e) if "AudioToUIMessage::INCREMENT:" in l)
iend = next(i for i in range(istart, len(e)) if e[i].strip() == "break;")
inc = e[istart + 1:iend]

out = ["// GENERATED by tools/make_original_scorer.py from analyser/original (Airwindows Meter 0.5.5). Do not edit by hand.",
       "#ifndef M_PI", "#  define M_PI (3.14159265358979323846)", "#endif",
       "#ifndef M_PI_2", "#  define M_PI_2 (1.57079632679489661923)", "#endif",
       "namespace f8korig {"] + struct + [""] + body + ["",
       "// The editor's handler for each INCREMENT message (one per audio window), copied from PluginEditor::idle().",
       "inline void editorOnIncrement(AirwindowsMeter& meter) {", "    bool repaintTS = false;"] + inc + ["    (void)repaintTS;", "}", "} // namespace f8korig", ""]
(here / "src" / "OriginalScorer.inc").write_text("\n".join(out))
print("wrote", len(out), "lines")
